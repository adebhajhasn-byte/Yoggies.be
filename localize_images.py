"""
localize_images.py — Yoggies.be image localization
==================================================
Downloads EVERY external image referenced in the source Excel and stores it
locally in site/images/, generating responsive WebP variants.

Why data-driven (Excel) instead of scraping the built HTML:
  The built HTML is regenerated by yoggies_pipeline.py on every run, so
  patching it is throwaway work. The Excel is the source of truth, so we
  localize there once and let the pipeline emit local paths forever after.

Output:
  site/images/<name>-200.webp    thumbnails (nav dropdown, category cards)
  site/images/<name>-600.webp    product gallery / mobile hero
  site/images/<name>-1200.webp   desktop hero / zoom
  site/images/<name>.<ext>       original fallback (SVG copied as-is)
  image_map.json                 {original_url: {thumb, md, lg, orig, w, h}}
  image_failures.txt             anything that could not be fetched

Safe to re-run: already-downloaded files are skipped, so an interrupted run
resumes where it stopped.

Requirements:
    pip install requests pillow openpyxl
Usage:
    python localize_images.py
    python localize_images.py --force        # re-download everything
    python localize_images.py --workers 12   # tune parallelism
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path
from urllib.parse import urlparse, urlsplit, urlunsplit

try:
    import requests
    from PIL import Image
    import openpyxl
except ImportError as exc:  # pragma: no cover
    sys.exit(f"Missing dependency ({exc.name}). Run: pip install requests pillow openpyxl")

# ── Configuration ─────────────────────────────────────────────────────────────
ROOT = Path(__file__).resolve().parent
XLSX = ROOT / "READY_FOR_BUILD_FINAL.xlsx"
SHEET = "READY_FOR_BUILD"
IMG_DIR = ROOT / "site" / "images"
MAP_FILE = ROOT / "image_map.json"
FAIL_FILE = ROOT / "image_failures.txt"

IMAGE_COLUMNS = ["image_main", "image_2", "image_3", "doglife_image", "icons_images"]

# The Excel covers product photos. Breed photos, hero banners and badge icons
# live in the atlas data module and the page templates, so scan those too.
EXTRA_SOURCES = [
    ROOT / "atlas_nl_data.py",
    ROOT / "yoggies_pipeline.py",
    ROOT / "templates" / "product.html",
    ROOT / "templates" / "hoofdpageproduct.html",
    ROOT / "templates" / "home.html",
    ROOT / "site" / "hondenatlas.html",
    ROOT / "site" / "Dierenkliniek.html",
    ROOT / "site" / "index.html",
]

# Hosts we localize. Anything else (e.g. fonts.googleapis.com) is left alone.
LOCALIZE_HOSTS = ("yoggies.cz", "doglife.be", "cdn.shopify.com", "image2url.com",
                  "img.youtube.com")

IMG_URL_RE = re.compile(
    r"https?://[^\s\"'<>()\\]+?\.(?:jpg|jpeg|png|webp|avif|gif|svg)(?:\?[^\s\"'<>()\\]*)?",
    re.IGNORECASE,
)

# Widths to generate. 200px covers the nav dropdown and category cards, which
# is where the current site wastes the most bandwidth (it loads 1200px files).
VARIANTS = {"thumb": 200, "md": 600, "lg": 1200}
WEBP_QUALITY = 82

TIMEOUT = 30
RETRIES = 3
BACKOFF = 2.0
HEADERS = {
    "User-Agent": (
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
        "(KHTML, like Gecko) Chrome/125.0 Safari/537.36"
    ),
    "Accept": "image/avif,image/webp,image/apng,image/*,*/*;q=0.8",
}

RASTER_EXT = {".jpg", ".jpeg", ".png", ".webp", ".avif", ".gif", ".bmp", ".tif", ".tiff"}


# ── URL handling ──────────────────────────────────────────────────────────────
def canonical_url(url: str) -> str:
    """Identity of an image, ignoring CDN sizing params.

    yoggies.cz serves the same file under many query strings
    (?width=1200&crop=center, ?width=30, ?v=1742896934...). Those are the same
    source file, so we key on the path and download the original once.
    """
    parts = urlsplit(url.strip())
    scheme = "https" if parts.scheme in ("http", "https", "") else parts.scheme
    netloc = parts.netloc.lower()
    if netloc.startswith("www."):
        netloc = netloc[4:]
    return urlunsplit((scheme, netloc, parts.path, "", ""))


def download_url(canonical: str) -> str:
    """Ask the CDN for the largest sensible rendition of a raster image."""
    ext = Path(urlparse(canonical).path).suffix.lower()
    if ext == ".svg":
        return canonical
    if "yoggies.cz/cdn/shop" in canonical or "cdn.shopify.com" in canonical:
        return f"{canonical}?width=1600"
    return canonical


def local_stem(canonical: str) -> str:
    """Readable, collision-free filename: <slug>-<hash8>."""
    name = Path(urlparse(canonical).path).name
    stem = Path(name).stem
    slug = re.sub(r"[^a-z0-9]+", "-", stem.lower()).strip("-")[:60] or "img"
    digest = hashlib.sha1(canonical.encode("utf-8")).hexdigest()[:8]
    return f"{slug}-{digest}"


# ── Excel harvesting ──────────────────────────────────────────────────────────
def collect_urls() -> dict[str, str]:
    """Return {canonical_url: original_url_as_written} from every image column."""
    if not XLSX.exists():
        sys.exit(f"Data file not found: {XLSX}")

    wb = openpyxl.load_workbook(XLSX, read_only=True, data_only=True)
    ws = wb[SHEET] if SHEET in wb.sheetnames else wb[wb.sheetnames[0]]
    rows = ws.iter_rows(values_only=True)
    header = {str(h): i for i, h in enumerate(next(rows)) if h}

    missing = [c for c in IMAGE_COLUMNS if c not in header]
    if missing:
        print(f"  ! columns not present, skipping: {', '.join(missing)}")

    found: dict[str, str] = {}
    for row in rows:
        for col in IMAGE_COLUMNS:
            idx = header.get(col)
            if idx is None or idx >= len(row) or not row[idx]:
                continue
            # icons_images packs several URLs separated by " | "
            for token in re.split(r"[|;,\s]+", str(row[idx])):
                token = token.strip()
                if token.startswith("http"):
                    found.setdefault(canonical_url(token), token)

    wb.close()

    # Breed photos / hero banners / badge icons that never pass through the Excel.
    for path in EXTRA_SOURCES:
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for token in IMG_URL_RE.findall(text):
            token = token.replace("&amp;", "&")
            host = urlparse(token).netloc.lower().removeprefix("www.")
            if host.endswith(LOCALIZE_HOSTS):
                found.setdefault(canonical_url(token), token)

    return found


# ── Download + derivatives ────────────────────────────────────────────────────
def fetch(url: str) -> bytes:
    last = None
    for attempt in range(1, RETRIES + 1):
        try:
            resp = requests.get(url, headers=HEADERS, timeout=TIMEOUT)
            resp.raise_for_status()
            if not resp.content:
                raise ValueError("empty response body")
            return resp.content
        except Exception as exc:  # noqa: BLE001 - report and retry
            last = exc
            if attempt < RETRIES:
                time.sleep(BACKOFF * attempt)
    raise RuntimeError(f"{type(last).__name__}: {last}")


def process(canonical: str, force: bool) -> dict:
    """Download one image and write its variants. Returns a map entry."""
    stem = local_stem(canonical)
    ext = Path(urlparse(canonical).path).suffix.lower() or ".jpg"
    original = IMG_DIR / f"{stem}{ext}"

    if force or not original.exists():
        original.write_bytes(fetch(download_url(canonical)))

    entry = {"orig": f"images/{original.name}"}

    # SVGs are already resolution-independent - no raster variants needed.
    if ext == ".svg":
        return entry

    if ext not in RASTER_EXT:
        return entry

    with Image.open(original) as im:
        im = im.convert("RGB") if im.mode in ("P", "RGBA", "LA") else im
        entry["w"], entry["h"] = im.size
        for key, width in VARIANTS.items():
            out = IMG_DIR / f"{stem}-{width}.webp"
            entry[key] = f"images/{out.name}"
            if out.exists() and not force:
                continue
            if im.width <= width and key != "thumb":
                # Never upscale; point larger keys at the source size.
                im.save(out, "WEBP", quality=WEBP_QUALITY, method=6)
                continue
            ratio = width / float(im.width)
            resized = im.resize((width, max(1, round(im.height * ratio))), Image.LANCZOS)
            resized.save(out, "WEBP", quality=WEBP_QUALITY, method=6)

    return entry


# ── Main ──────────────────────────────────────────────────────────────────────
def main() -> int:
    ap = argparse.ArgumentParser(description="Localize all Yoggies product images.")
    ap.add_argument("--force", action="store_true", help="re-download and re-encode everything")
    ap.add_argument("--workers", type=int, default=8, help="parallel downloads (default 8)")
    args = ap.parse_args()

    IMG_DIR.mkdir(parents=True, exist_ok=True)

    print("Reading image URLs from Excel...")
    urls = collect_urls()
    print(f"  {len(urls)} unique images to localize\n")

    mapping: dict[str, dict] = {}
    failures: list[tuple[str, str]] = []
    done = 0

    with ThreadPoolExecutor(max_workers=args.workers) as pool:
        futures = {pool.submit(process, c, args.force): c for c in urls}
        for future in as_completed(futures):
            canonical = futures[future]
            done += 1
            try:
                mapping[canonical] = future.result()
                status = "ok"
            except Exception as exc:  # noqa: BLE001 - collected into a report
                failures.append((canonical, str(exc)))
                status = f"FAIL {exc}"
            print(f"  [{done}/{len(urls)}] {status}  {canonical[:88]}")

    # Also key the map by every original spelling so the pipeline can look up
    # whatever string happens to sit in the Excel cell.
    full_map = dict(mapping)
    for canonical, original in urls.items():
        if canonical in mapping and original != canonical:
            full_map[original] = mapping[canonical]

    MAP_FILE.write_text(json.dumps(full_map, indent=2, ensure_ascii=False), encoding="utf-8")

    if failures:
        FAIL_FILE.write_text(
            "\n".join(f"{u}\t{e}" for u, e in failures), encoding="utf-8"
        )

    total_mb = sum(f.stat().st_size for f in IMG_DIR.glob("*")) / 1_048_576
    print(
        f"\nDone. {len(mapping)} localized, {len(failures)} failed, "
        f"{total_mb:.1f} MB in site/images/"
    )
    print(f"Map written to {MAP_FILE.name}")
    if failures:
        print(f"Failures listed in {FAIL_FILE.name} - re-run to retry them.")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
